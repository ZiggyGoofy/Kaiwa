// Replaces the French texts with English ones (same order), and checks the lists line up.
function applyEnglishContent() {
  const fill = (target, src, idx) => {
    for (const k in src) {
      const [title, list] = src[k], items = target[k].items;
      if (list.length !== items.length) { console.warn("EN content mismatch:", k); continue; }
      target[k].title = title;
      items.forEach((it, i) => {
        if (Array.isArray(list[i])) idx.forEach((pos, j) => (it[pos] = list[i][j]));
        else it[idx[0]] = list[i];
      });
    }
  };
  fill(PHRASES, CONTENT_EN.phrases, [2]);
  fill(VOCAB, CONTENT_EN.vocab, [2]);
  fill(PARTICLES, CONTENT_EN.particles, [4, 5]);
  if (CONTENT_EN.words.length === WORDS_OF_DAY.length) {
    WORDS_OF_DAY.forEach((w, i) => { w[2] = CONTENT_EN.words[i][0]; w[4] = CONTENT_EN.words[i][1]; });
  } else console.warn("EN content mismatch: words");
}
if (LANG === "en") applyEnglishContent();
